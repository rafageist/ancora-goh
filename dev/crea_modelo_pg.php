	$tables = $db->getAsArray("select * from information_schema.tables where table_type='BASE TABLE' and table_schema<>'pg_catalog' AND table_schema<>'information_schema' order by table_schema");
	
	prints("[INFO] Creando modelo principal $dbname.json");
	
