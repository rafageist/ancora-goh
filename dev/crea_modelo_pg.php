    }
    fputs($fichero,"\n".'              ],'."\n");
    
    $vistas = $db->getAsArray("select * from information_schema.views");
        
    fputs($fichero,"\n".'    viewdefs: ['."\n");
    
    $primero=true;
    foreach ($vistas as $vista){
    	$table_schema = $vista['table_schema'];
		$table_name= $vista['table_name'];
        
        if (ValidSchema($table_schema)==false) continue;
        
        if ($primero==false) fputs($fichero,", \n");
        
        fputs($fichero,"	            \"".$table_schema.".".$table_name.".json\"");   
        
        $primero=false;
        
    }
    fputs($fichero,"\n".'              ],'."\n");
     
     
    fputs($fichero,"\n".'    functiondefs: ['."\n"); 
     
    $funciones =  $db->getAsArray("select * from information_schema.routines where specific_schema <> 'pg_catalog' and specific_schema <> 'information_schema' order by specific_schema");
    $primero = true;
    foreach ($funciones as $funcion){
    	$schema = $funcion['specific_schema'];
		if (ValidSchema($schema)==false) continue;
        if ($primero==false) fputs($fichero,", \n");
        $primero=false;
        fputs($fichero,'                  "'.$schema.".".$funcion['specific_name'].'.json"'); 
    }
    
    fputs($fichero,"\n".'              ]'."\n");
    fputs($fichero,"\n".'   }'."\n");
    fputs($fichero,'}'."\n");
 	fclose($fichero);
    
    foreach ($funciones as $funcion){
    	$schema = $funcion['specific_schema'];
        prints("[INFO] Creando model para funcion $schema.{$funcion['routine_name']}");
		if (ValidSchema($schema)==false) continue;
        $fichero=fopen($foldersrc."/".$schema.".".$funcion['specific_name'].".json","w");
        
        
        fputs($fichero,"/** \n");
        fputs($fichero,"  *  _______________________________________ /    /\n");
        fputs($fichero,"  * |                                       |    /\n");
        fputs($fichero,"  * |          cogePHP JSON SubModel        |   /\n");
        fputs($fichero,"  * |   generated by cogePHP Model Creator  |  /\n");
        fputs($fichero,"  * |         from a PostgreSQL function    | /\n");
        fputs($fichero,"  * |_______________________________________|/\n");
        fputs($fichero,"  *  - - - - - - - - - - - - - - - - - - - - \n");
        fputs($fichero,"  * |    schema: $schema \n");
        fputs($fichero,"  * |  function: ".$funcion['routine_name']." \n");
        fputs($fichero,"  *  - - - - - - - - - - - - - - - - - -  \n");
        fputs($fichero,"  */ \n");
        fputs($fichero,"  //-$ $fecha \n");
        fputs($fichero,"\n");
        fputs($fichero,'{'."\n");
        fputs($fichero,'   schema: "'.$funcion['specific_schema'].'",'."\n");
        fputs($fichero,'     name: "'.$funcion['routine_name'].'",'."\n");
        fputs($fichero,'   return: "'.$funcion['data_type'].'",'."\n");
        fputs($fichero,'   return_specific: "'.$funcion['type_udt_name'].'",'."\n");
        fputs($fichero,'   params: ['."\n");
        
        $parametros =  $db->getAsArray("select * from information_schema.parameters where specific_name = '".$funcion['specific_name']."' order by ordinal_position");
        
        $ini = true;
        if (is_array($parametros))
        foreach ($parametros as $param){
            if ($ini==false) fputs($fichero,", \n");
            $ini=false;
            fputs($fichero,'         {'."\n");
            fputs($fichero,'            name: "'.$param['parameter_name'].'",'."\n");          
            fputs($fichero,'       data_type: "'.getMapaType($param['data_type']).'",'."\n");          
            fputs($fichero,'            mode: "'.$param['parameter_mode'].'"'."\n");          
            fputs($fichero,'         }');
        }
        
        fputs($fichero,"\n".'       ]'."\n");        
        fputs($fichero,"\n".'}'."\n");   
     }
    
      
    if ($fichero!=null) fclose($fichero);
    
	foreach ($tables as $table){
		
		$table_schema = $table['table_schema'];
		$table_name= $table['table_name'];
        
        //ignorando tablas
        if (isset($ignora_tabla["$table_schema.$table_name"]))
                {prints("[INFO] Ignorando tabla $table_schema.$table_name"); continue;}

        
		if (ValidSchema($table_schema)==false) continue;
        
        $fichero=fopen($foldersrc."/".$table_schema.".".$table_name.".json","w");
		
		prints("[INFO] Creando...".$table_schema.".".$table_name."\n");
        
        fputs($fichero,"/** \n");
        fputs($fichero,"  *  _______________________________________ /    /\n");
        fputs($fichero,"  * |                                       |    /\n");
        fputs($fichero,"  * |          cogePHP JSON SubModel        |   /\n");
        fputs($fichero,"  * |   generated by PHP-MDA Model Creator  |  /\n");
        fputs($fichero,"  * |         from a PostgreSQL table       | /\n");
        fputs($fichero,"  * |_______________________________________|/\n");
        fputs($fichero,"  *  - - - - - - - - - - - - - - - - - - - - \n");
        fputs($fichero,"  * | schema: $table_schema \n");
        fputs($fichero,"  * |  table: $table_name \n");
        fputs($fichero,"  *  - - - - - - - - - - - - - - - - - -  \n");
        fputs($fichero,"  */ \n");
        fputs($fichero,"  //-$ $fecha \n");
        fputs($fichero,"\n");
		fputs($fichero,"{ \n");
        if ($table_schema!='public') 
            fputs($fichero,'  schema: "'.$table_schema.'",'."\n");
        else
            fputs($fichero,'  schema: "",'."\n");	    fputs($fichero,'    name: "'.$table_name.'",'."\n");
	    fputs($fichero,'   title: "'.$table_name.'",'."\n");
	    fputs($fichero,'  plural: "'.$table_name.'",'."\n");
	    fputs($fichero,"  fields: ["."\n");
	
		$columns = $db->getAsArray("select * from information_schema.columns where table_schema='$table_schema' and table_name='$table_name';");
        $i=0;
        foreach($columns as $column){
                
            //ignorando columnas
            if (isset($ignora_columna["$table_schema.$table_name.{$column['column_name']}"]))
                         {prints("[INFO] Ignorando columna $table_schema.$table_name.{$column['column_name']}"); continue;}
            
            $i++;
            if ($i>1) fputs($fichero,','."\n");
            $nulo='false';
            if ($column['is_nullable']=="YES") $nulo='true';

            $unico = 'false'; //TODO: falta sacarlo de la metadata
            
            if ($column['character_maximum_length']=='') $long='255'; else $long=$column['character_maximum_length'];
            
            $type = getMapaType($column['data_type']);
            if ($column['column_name']=="id" && $type =="string") $type="replica";
            if ($column['column_name']=="contrasena" && $type =="string") $type="md5";
            
            fputs($fichero,'            {'."\n");
            fputs($fichero,'                 name: "'.$column['column_name'].'", '."\n");
            fputs($fichero,'                 type: "'.$type.'", '."\n");
            fputs($fichero,'                 long: '.$long.','."\n"); 
            fputs($fichero,'            allownull: '.$nulo.','."\n"); 
            fputs($fichero,'               unique: '.$unico."\n"); 
            fputs($fichero,'            }');
        }
	    
    $pconstraints = $db->getAsArray("select * from information_schema.table_constraints where table_schema='$table_schema' and table_name='$table_name' and constraint_type='PRIMARY KEY';");
    
    $llave = "";
    $ya = array();
    if (is_array($pconstraints))
     foreach ($pconstraints as $row){
        $fieldn = $db->getAsArray("select * from information_schema.constraint_column_usage where constraint_name='".$row['constraint_name']."';");
        $primera = true;    
        foreach ($fieldn as $r) {
            if (!isset($ya[$r['column_name']])) { // a veces sale repetido un campo 
                                                // �podre resolverlo con un group by en la consulta?
                if ($primera == false) $llave .= ', ';
                $llave .='"'.$r['column_name'].'"';
                $primera=false;
                $ya[$r['column_name']]=true;
            }
        }
    }
    
    $rkeys = $db->getAsArray("select * from information_schema.key_column_usage");   
   
    $fconstraints = $db->getAsArray("select * from information_schema.table_constraints where table_schema='$table_schema' and table_name='$table_name' and constraint_type='FOREIGN KEY';");    
     
    $foraneas="";
    $primera = true;
    if (is_array($fconstraints))
      foreach ($fconstraints as $row){
        if ($primera == false) $foraneas .= ", \n";
        $primera = false;
        $foraneas .= '                   {'."\n".'                    fields: ['."\n";
        
        $fieldn = $db->getAsArray("select * from information_schema.key_column_usage where constraint_name='".$row['constraint_name']."' order by ordinal_position;");
        $fieldnn = $db->getAsArray("select * from information_schema.constraint_column_usage where constraint_name='".$row['constraint_name']."';");        
        
        $ff = "";
        $primero = true; 
        foreach ($fieldn as $k=>$r) {
            if ($primero == false) $ff .= ", \n";
            $primero = false;
            $ff .= '                              {'."\n".'                                localfield: "'.$r['column_name'].'", '."\n".'                                foreign_key: "'.$fieldnn[$k]['column_name'].'"'."\n".'                              }';
        }
        $foraneas .= $ff."\n".'                            ], '."\n".'                    foreign_schema: "'.$fieldnn[0]['table_schema'].'",'."\n".'                    foreign_table: "'.$fieldnn[0]['table_name'].'", '."\n".'                    on_delete_cascade: true, '."\n".'                    on_update_cascade: true'."\n".'                   }';
        }
    
    fputs($fichero,"\n".'   ],'."\n".'   primary_key: ['.$llave.'],'."\n".'   foreign_keys: ['."\n".$foraneas."\n".'               ]'."\n");
    fputs($fichero," }\n");
    fclose($fichero);
    }
	
     foreach ($vistas as $vista){
    	$table_schema = $vista['table_schema'];
		$table_name= $vista['table_name'];
        if (ValidSchema($table_schema)==false) continue;
        $fichero=fopen($foldersrc."/".$table_schema.".".$table_name.".json","w");
		
		prints("[INFO] Creando...".$table_schema.".".$table_name."\n");
        
        fputs($fichero,"/** \n");
        fputs($fichero,"  *  _______________________________________ /    /\n");
        fputs($fichero,"  * |                                       |    /\n");
        fputs($fichero,"  * |          cogePHP JSON SubModel        |   /\n");
        fputs($fichero,"  * |   generated by PHP-MDA Model Creator  |  /\n");
        fputs($fichero,"  * |         from a PostgreSQL view        | /\n");
        fputs($fichero,"  * |_______________________________________|/\n");
        fputs($fichero,"  *  - - - - - - - - - - - - - - - - - - - - \n");
        fputs($fichero,"  * | schema: $table_schema \n");
        fputs($fichero,"  * |   view: $table_name \n");
        fputs($fichero,"  *  - - - - - - - - - - - - - - - - - -  \n");
        fputs($fichero,"  */ \n");
        fputs($fichero,"  //-$ $fecha \n");
        fputs($fichero,"\n");
                        
        fputs($fichero,"{ \n");
	    fputs($fichero,'  schema: "'.$table_schema.'",'."\n");
	    fputs($fichero,'    name: "'.$table_name.'",'."\n");
	    fputs($fichero,'   title: "'.$table_name.'",'."\n");
	    fputs($fichero,'  plural: "'.$table_name.'",'."\n");
        fputs($fichero,'     SQL: "'.$vista['view_definition'].'",'."\n");
        fputs($fichero,"} \n");
                
    }
    
    prints("[INFO] Generacion terminada con exito!")  
