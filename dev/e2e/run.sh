#!/usr/bin/env bash
# Local-only end-to-end scheduling run through PHP and PostgreSQL (issue #25).
#
#   dev/sql/tools/with-ephemeral-pg.sh dev/e2e/run.sh
#
# What it does, against a disposable PostgreSQL cluster (verified by
# dev/sql/tools/disposable-guard.sh) and a copy of the git-tracked files in a
# temporary directory (the working tree is never written):
#   1. installs the schema with the data seed and the synthetic organization
#      in dev/e2e/fixture.sql (no historical data);
#   2. writes a throwaway bin/ancoragoh.conf for that cluster, sets the
#      administrator password with bin/setpassword.php and creates a user
#      without roles with bin/adduser.php (random per-run passwords);
#   3. starts the PHP built-in web server bound to 127.0.0.1 only;
#   4. drives the application over HTTP like the browser client does
#      (www/js/app/server/*.js): login, an access denial, data entry and
#      listing, assignments, generation through control/custom/generar.php,
#      timetable readback, the anonymous viewer, logout;
#   5. checks the placements in the database (demand, collisions, overflow)
#      and fails on any PHP warning, error or TypeError and on any SQL error
#      in the PostgreSQL server log.
# Every step has a hard time limit. The web server, the temporary copy and
# (through the launcher) the cluster are removed on exit, also on failure.
#
# The legacy application is NOT safe for any network: SQL injection in the
# generated layer, no CSRF protection and no output escaping remain
# (docs/modernization/php-auth-hardening.md §6). This harness never listens
# on anything but the loopback interface.
#
# Exit status 0 only if every check passes.
set -uo pipefail

repo=$(cd "$(dirname "$0")/../.." && pwd)
. "$repo/dev/sql/tools/disposable-guard.sh"
agoh_require_disposable || exit 3

PHP=${PHP:-php}
STEP_TIMEOUT=${E2E_STEP_TIMEOUT:-30}     # seconds per HTTP request
GEN_TIMEOUT=${E2E_GEN_TIMEOUT:-120}      # seconds for the generation request
db=agoh_e2e

work=$(mktemp -d "${TMPDIR:-/tmp}/agoh-e2e.XXXXXX")
web_pid=""
cleanup() {
  [ -n "$web_pid" ] && kill "$web_pid" 2>/dev/null && wait "$web_pid" 2>/dev/null
  rm -rf "$work"
}
trap cleanup EXIT

pass=0; fail=0
ok()  { pass=$((pass + 1)); printf 'PASS  %s\n' "$1"; }
bad() { fail=$((fail + 1)); printf 'FAIL  %s\n' "$1"; [ -n "${2:-}" ] && printf '      %s\n' "$2"; }
check() { # description, command...
  local d=$1; shift
  if "$@"; then ok "$d"; else bad "$d"; fi
}
sql() { psql -X -At -v ON_ERROR_STOP=1 -d "$db" -c "$1"; }
randpw() { od -An -N12 -tx1 /dev/urandom | tr -d ' \n'; }

# ------------------------------------------------------------------ 1. database
echo "# database: install schema + seed, load synthetic fixture"
if ! "$repo/dev/sql/install.sh" --with-data "$db" >"$work/install.log" 2>&1; then
  cat "$work/install.log"; echo "FAIL  installation"; exit 1
fi
psql -X -q -v ON_ERROR_STOP=1 -d "$db" -f "$repo/dev/e2e/fixture.sql" >/dev/null || { echo "FAIL  fixture"; exit 1; }
# metrics helpers of the SQL characterization suite (tst schema)
psql -X -q -v ON_ERROR_STOP=1 -d "$db" -f "$repo/dev/sql/tests/fixtures/helpers.sql" >/dev/null || { echo "FAIL  helpers"; exit 1; }
pg_log="$PGHOST/server.log"   # written by with-ephemeral-pg.sh
pg_log_start=$(wc -l < "$pg_log")

# ------------------------------------------------------------------ 2. application copy
echo "# application: temporary copy of the tracked files"
app=$work/app
mkdir -p "$app"
git -C "$repo" ls-files -z | (cd "$repo" && tar --null -T - -cf -) | tar -xf - -C "$app"
cat > "$app/bin/ancoragoh.conf" <<EOF
# generated by dev/e2e/run.sh for one run; trust authentication on a socket-only cluster
host = "$PGHOST"
port = $PGPORT
dbname = "$db"
user = "$PGUSER"
password = "unused-trust-auth"
EOF
admin_pw=$(randpw); plain_pw=$(randpw)
check "seeded administrator has no usable password before setpassword" \
  test "$(sql "SELECT contrasena LIKE '!%' FROM seguridad.usuario WHERE nick = 'admin'")" = t
(cd "$app/bin" && printf '%s\n' "$admin_pw" | "$PHP" setpassword.php -nick admin) >"$work/cli.log" 2>&1
check "bin/setpassword.php sets the administrator password (password_hash)" \
  test "$(sql "SELECT contrasena LIKE '\$2y\$%' FROM seguridad.usuario WHERE nick = 'admin'")" = t
(cd "$app/bin" && printf '%s\n' "$plain_pw" | "$PHP" adduser.php -nick e2e_plain -nombre 'Plain user' -correo plain@example.org) >>"$work/cli.log" 2>&1
check "bin/adduser.php creates a user without roles" \
  test "$(sql "SELECT count(*) FROM seguridad.usuario u WHERE nick = 'e2e_plain' AND NOT EXISTS (SELECT 1 FROM seguridad.rol_de_usuario r WHERE r.usuario = u.id)")" = 1

# ------------------------------------------------------------------ 3. web server (loopback only)
port=""
for p in $(seq 18080 18180); do
  if ! (exec 3<>"/dev/tcp/127.0.0.1/$p") 2>/dev/null; then port=$p; break; fi
done
[ -n "$port" ] || { echo "FAIL  no free loopback port"; exit 1; }
php_log=$work/php-errors.log; : > "$php_log"
(
  cd "$app/www" || exit 1
  # statement_timeout bounds every query of the application (libpq PGOPTIONS)
  PGOPTIONS="-c statement_timeout=${GEN_TIMEOUT}s" exec "$PHP" -S "127.0.0.1:$port" -t . \
    -d display_errors=0 -d log_errors=1 -d error_log="$php_log" -d error_reporting=E_ALL \
    -d session.save_path="$work" -d max_execution_time=0
) >"$work/web.log" 2>&1 &
web_pid=$!
for _ in $(seq 1 50); do (exec 3<>"/dev/tcp/127.0.0.1/$port") 2>/dev/null && break; sleep 0.1; done
base="http://127.0.0.1:$port/index.php"

listen=$(ss -Hltnp 2>/dev/null | grep "pid=$web_pid," | awk '{print $4}' | sort -u | tr '\n' ' ')
check "web server listens on the loopback interface only ($listen)" test "$listen" = "127.0.0.1:$port "

# curl wrappers: one cookie jar per client; responses are kept for inspection
req() { # jar name, output file, max time, curl args...
  local jar=$work/$1.jar out=$work/$2 max=$3; shift 3
  curl -sS -o "$out" -D "$out.h" -w '%{http_code}' --max-time "$max" -b "$jar" -c "$jar" "$@"
}
event() { # jar, output, max time, event, field=value...
  local jar=$1 out=$2 max=$3 ev=$4; shift 4
  local args=(--data-urlencode "app_event_$ev=yes")
  for kv in "$@"; do args+=(--data-urlencode "$kv"); done
  req "$jar" "$out" "$max" "$base?execute" "${args[@]}"
}
has() { grep -qF -- "$2" "$work/$1"; }

# ------------------------------------------------------------------ 4. HTTP flows
echo "# http: anonymous"
code=$(req anon login.html "$STEP_TIMEOUT" "$base")
check "GET / returns the login form (HTTP $code)" bash -c "[ $code = 200 ] && grep -q 'name=\"edtUser\"' '$work/login.html'"
check "login page does not offer the anonymous timetable viewer" bash -c "! grep -q 'browsers.publico.show' '$work/login.html'"
code=$(event anon anon-viewer.html "$STEP_TIMEOUT" get_browser_publico access=public)
check "anonymous viewer event is refused (session expired)" has anon-viewer.html 'message-session-expired'
code=$(event anon anon-add.html "$STEP_TIMEOUT" add_Profesor field_Profesor_nombre=Intruder)
check "anonymous data change is refused and writes nothing" \
  bash -c "grep -qF 'message-session-expired' '$work/anon-add.html' && [ \"\$(psql -X -At -d $db -c \"SELECT count(*) FROM profesor WHERE nombre = 'Intruder'\")\" = 0 ]"

echo "# http: login"
code=$(req admin wrong.html "$STEP_TIMEOUT" "$base" --data-urlencode btnLogin=Entrar --data-urlencode edtUser=admin --data-urlencode "edtPass=wrong-$admin_pw")
check "wrong password is denied" has wrong.html 'access_denied'
sid_before=$(awk '$6 == "PHPSESSID" {print $7}' "$work/admin.jar")
code=$(req admin app.html "$STEP_TIMEOUT" "$base" --data-urlencode btnLogin=Entrar --data-urlencode edtUser=admin --data-urlencode "edtPass=$admin_pw")
sid_after=$(awk '$6 == "PHPSESSID" {print $7}' "$work/admin.jar")
check "administrator logs in with the password set by setpassword (HTTP $code)" \
  bash -c "[ $code = 200 ] && ! grep -q 'access_denied' '$work/app.html' && ! grep -q 'name=\"edtUser\"' '$work/app.html'"
check "session id changes at login" bash -c "[ -n '$sid_after' ] && [ '$sid_before' != '$sid_after' ]"
check "session cookie is HttpOnly and SameSite=Lax" bash -c "grep -i '^set-cookie: PHPSESSID=' '$work/app.html.h' | tail -1 | grep -qi 'httponly' && grep -i '^set-cookie: PHPSESSID=' '$work/app.html.h' | tail -1 | grep -qi 'samesite=lax'"

echo "# http: access denial"
code=$(req plain plain.html "$STEP_TIMEOUT" "$base" --data-urlencode btnLogin=Entrar --data-urlencode edtUser=e2e_plain --data-urlencode "edtPass=$plain_pw")
check "user without roles logs in" bash -c "! grep -q 'access_denied' '$work/plain.html'"
code=$(event plain plain-add.html "$STEP_TIMEOUT" add_Profesor field_Profesor_nombre=Unauthorized)
check "user without permission is denied an event and nothing is written" \
  bash -c "grep -qF 'access_denied' '$work/plain-add.html' && [ \"\$(psql -X -At -d $db -c \"SELECT count(*) FROM profesor WHERE nombre = 'Unauthorized'\")\" = 0 ]"

echo "# http: data entry and listing (administrator)"
code=$(event admin add-teacher.html "$STEP_TIMEOUT" add_Profesor "field_Profesor_nombre=Teacher Beta")
tb=$(sql "SELECT id FROM profesor WHERE nombre = 'Teacher Beta'")
check "add_Profesor creates the teacher, owned by the administrator (HTTP $code)" \
  test "$(sql "SELECT count(*) FROM profesor WHERE nombre = 'Teacher Beta' AND creador = 'admin-superuser'")" = 1
code=$(event admin list-teachers.html "$STEP_TIMEOUT" custom_getui_ExploradorListProfesores)
check "the teacher list shows the new teacher (HTTP $code)" has list-teachers.html 'Teacher Beta'
for t in B1 B2; do
  code=$(event admin "assign-$t.html" "$STEP_TIMEOUT" add_ProfesorParaActividad "field_ProfesorParaActividad_profesor=$tb" "field_ProfesorParaActividad_plantilla=$t" field_ProfesorParaActividad_prioridad=1)
done
check "add_ProfesorParaActividad assigns the teacher to templates B1 and B2" \
  test "$(sql "SELECT count(*) FROM profesor_para_actividad WHERE profesor = '$tb' AND plantilla IN ('B1', 'B2')")" = 2
for row in $(sql "SELECT id FROM profesor_para_actividad WHERE profesor = '$tb' ORDER BY plantilla"); do
  for g in G1 G2; do
    code=$(event admin "pxg-$row-$g.html" "$STEP_TIMEOUT" custom_ActualizaProfesorParaGrupo "pxact=$row" "grupo=$g")
  done
done
check "custom_ActualizaProfesorParaGrupo assigns both groups to both assignments" \
  test "$(sql "SELECT count(*) FROM profesor_para_grupo g JOIN profesor_para_actividad a ON a.id = g.profesor_para_actividad WHERE a.profesor = '$tb'")" = 4

echo "# http: generation"
start=$(date +%s)
code=$(event admin generate.html "$GEN_TIMEOUT" generar esp=E nivel=N periodo=PER forma=1 parche=false compactar=0 parche1=false buscalugar=false)
took=$(( $(date +%s) - start ))
check "generar request completes within ${GEN_TIMEOUT}s (HTTP $code, ${took}s)" test "$code" = 200
metrics=$(sql "SELECT tst.metrics('E', 'N', 'PER')" | sed 's/^METRIC //')
echo "      METRIC $metrics"
check "every demand is placed: 8 of 8, no collision, no overflow" test "$metrics" = "demands=8 placed=8 unplaced=0 collisions=0 overflow=0"
check "every placement has a teacher and a room of its template" \
  test "$(sql "SELECT count(*) FROM actividad a WHERE NOT EXISTS (SELECT 1 FROM profesor_para_actividad p WHERE p.plantilla = a.plantilla AND p.profesor = a.profesor) OR NOT EXISTS (SELECT 1 FROM lugar_para_actividad l WHERE l.plantilla = a.plantilla AND l.lugar = a.lugar)")" = 0
# teacher by name: ids created over HTTP are random per run
placements=$(sql "SELECT string_agg(a.plantilla || '/' || a.grupo || '/' || p.nombre || '/' || a.lugar || '/' || a.dia || '/' || a.turno, ',' ORDER BY a.plantilla, a.grupo) FROM actividad a JOIN profesor p ON p.id = a.profesor")
printf '%s\n' "$placements" | tr ',' '\n' | sed 's/^/        /'
digest=$(printf '%s' "$placements" | md5sum | cut -d' ' -f1)
echo "      placement digest $digest"
expected_digest=$(grep -v '^#' "$repo/dev/e2e/expected-placements.md5" 2>/dev/null | head -1)
check "placements are deterministic (dev/e2e/expected-placements.md5)" test "$digest" = "$expected_digest"

echo "# http: timetable readback"
code=$(event admin tt-B1.html "$STEP_TIMEOUT" get_minibrowser_horarios idbrg=B1 idperiodo=PER)
check "group timetable for B1 lists both subjects and both teachers (HTTP $code)" \
  bash -c "for w in 'Subject Alpha' 'Subject Beta' 'Teacher Alpha' 'Teacher Beta'; do grep -qF \"\$w\" '$work/tt-B1.html' || exit 1; done"
code=$(event admin tt-T.html "$STEP_TIMEOUT" get_minibrowser_horarios "idprofe=$tb" idperiodo=PER)
check "teacher timetable for Teacher Beta shows its 4 activities" \
  test "$(grep -oF 'Subject Beta' "$work/tt-T.html" | wc -l)" -ge 4

echo "# http: anonymous viewer after generation, logout"
code=$(event anon anon-tt.html "$STEP_TIMEOUT" get_minibrowser_publico idbrg=B1 idperiodo=PER access=public)
check "anonymous timetable request is still refused" bash -c "grep -qF 'message-session-expired' '$work/anon-tt.html' && ! grep -qF 'Subject Alpha' '$work/anon-tt.html'"
code=$(req admin logout.html "$STEP_TIMEOUT" "$base?logout")
code=$(event admin after-logout.html "$STEP_TIMEOUT" custom_getui_ExploradorListProfesores)
check "after logout the session no longer runs events" has after-logout.html 'message-session-expired'

# ------------------------------------------------------------------ 5. logs
kill "$web_pid" 2>/dev/null; wait "$web_pid" 2>/dev/null; web_pid=""
php_bad=$(grep -E 'PHP (Warning|Fatal error|Parse error|Recoverable fatal error)|TypeError|ArgumentCountError|Uncaught' "$php_log" | sort | uniq -c | sort -rn)
check "no PHP warning, fatal error or TypeError in the web server log" test -z "$php_bad"
[ -n "$php_bad" ] && printf '%s\n' "$php_bad" | head -20 | sed 's/^/      /'
php_notice=$(grep -cE 'PHP (Notice|Deprecated)' "$php_log")
echo "      PHP notices/deprecations (reported, not failing): $php_notice"
grep -E 'PHP (Notice|Deprecated)' "$php_log" | sed -E 's/^\[[^]]*\] //' | sort | uniq -c | sort -rn | head -10 | sed 's/^/        /'
sql_err=$(tail -n +"$((pg_log_start + 1))" "$pg_log" | grep -E 'ERROR:|FATAL:|PANIC:' | sort | uniq -c)
check "no SQL error in the PostgreSQL server log" test -z "$sql_err"
[ -n "$sql_err" ] && printf '%s\n' "$sql_err" | head -20 | sed 's/^/      /'

echo "# e2e: $pass passed, $fail failed"
[ "$fail" = 0 ]
